"""Bounded clean-room reader for one exact LabSolutions result ASCII profile."""

from __future__ import annotations

import hashlib
import os
import re
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from math import isfinite
from pathlib import Path
from typing import Any

MAX_RESULT_ASCII_BYTES = 32 * 1024 * 1024
MAX_RESULT_ASCII_LINES = 1_000_000
MAX_LINE_CHARACTERS = 32_767
MAX_NUMERIC_LEXEME_CHARACTERS = 128
MAX_PEAKS = 100_000
MAX_CHROMATOGRAM_POINTS = 900_000

SECTION_ORDER = (
    "[Header]",
    "[File Information]",
    "[Sample Information]",
    "[Original Files]",
    "[File Description]",
    "[Configuration]",
    "[Peak Table(Ch1)]",
    "[Compound Results(Ch1)]",
    "[Chromatogram (Ch1)]",
)
PEAK_HEADERS = (
    "Peak#",
    "R.Time",
    "I.Time",
    "F.Time",
    "Area",
    "Height",
    "A/H",
    "Conc.",
    "Mark",
    "ID#",
    "Name",
    "k'",
    "Plate #",
    "Plate Ht.",
    "Tailing",
    "Resolution",
    "Sep.Factor",
    "Area Ratio",
    "Height Ratio",
    "Conc. %",
    "Norm Conc.",
)
HEADER_KEYS = ("Application Name", "Version", "Data File Name", "Output Date", "Output Time")
FILE_INFORMATION_KEYS = ("Type", "Generated", "Generated by", "Modified", "Modified by")
SAMPLE_INFORMATION_KEYS = (
    "Operator Name",
    "Acquired",
    "Sample Type",
    "Level",
    "Sample Name",
    "Sample ID",
    *(f"ISTD Amount{index}" for index in range(1, 33)),
    "Sample Amount",
    "Dilution Factor",
    "Vial#",
    "Injection Volume",
    "Injection Count",
    "Bar Code",
)
ORIGINAL_FILES_KEYS = ("Data File", "Method File", "Batch File", "Report Format File")
CONFIGURATION_KEYS = (
    "Instrument Name",
    "Instrument #",
    "Line #",
    "# of Detectors",
    "Detector ID",
    "Detector Name",
    "# of Channels",
)

_FAMILY_MARKER = b"Application Name\tLabSolutions"
_DECIMAL = re.compile(r"[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)\Z")
_POSITIVE_INTEGER = re.compile(r"[1-9][0-9]*\Z")
_NONNEGATIVE_INTEGER = re.compile(r"(?:0|[1-9][0-9]*)\Z")


class ShimadzuResultAsciiStructureError(Exception):
    """Privacy-safe structural error translated by the public adapter."""

    def __init__(self, code: str, message: str, **details: Any) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details


@dataclass(frozen=True, slots=True)
class ShimadzuResultPeak:
    """One source-order peak row from the exact result table."""

    peak_number: int
    observation_order: int
    retention_time_text: str
    retention_time: float
    start_time_text: str
    start_time: float
    end_time_text: str
    end_time: float
    area_text: str
    area: float
    height_text: str
    height: float


@dataclass(frozen=True, slots=True)
class ShimadzuResultAsciiData:
    """Allowlisted scientific and profile facts from the exact ASCII source."""

    application_name: str
    software_version: str
    instrument_model: str
    source_detector_label: str
    source_channel: str
    retention_time_unit: str
    peaks: tuple[ShimadzuResultPeak, ...]
    chromatogram_interval_ms: int
    chromatogram_point_count: int
    source_size: int
    source_sha256: str


def _fail(code: str, message: str, **details: Any) -> ShimadzuResultAsciiStructureError:
    return ShimadzuResultAsciiStructureError(code, message, **details)


def _read_bytes(path: Path) -> bytes:
    try:
        with path.open("rb") as stream:
            size = os.fstat(stream.fileno()).st_size
            if size < len(_FAMILY_MARKER) or size > MAX_RESULT_ASCII_BYTES:
                raise _fail(
                    "SHIMADZU_RESULT_ASCII_SIZE_INVALID",
                    "The result ASCII file size is outside the supported bounded profile.",
                    size_bytes=size,
                    maximum_bytes=MAX_RESULT_ASCII_BYTES,
                )
            data = stream.read(MAX_RESULT_ASCII_BYTES + 1)
            extra = stream.read(1)
    except ShimadzuResultAsciiStructureError:
        raise
    except OSError as error:
        raise _fail("INPUT_READ_FAILED", "The result ASCII input could not be read.") from error
    if len(data) > MAX_RESULT_ASCII_BYTES or extra or len(data) != size:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_SIZE_CHANGED",
            "The result ASCII size changed during its bounded read.",
        )
    return data


def has_result_ascii_family_identity(path: Path) -> bool:
    """Return whether a bounded prefix identifies the LabSolutions result family."""
    try:
        with path.open("rb") as stream:
            prefix = stream.read(128 * 1024)
    except OSError:
        return False
    return _FAMILY_MARKER in prefix


def _lines(data: bytes) -> tuple[str, ...]:
    if data.startswith(b"\xef\xbb\xbf") or b"\x00" in data:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_ENCODING_UNSUPPORTED",
            "The exact result ASCII profile requires unmarked single-byte ASCII text.",
        )
    line_count = data.count(b"\r\n")
    if line_count > MAX_RESULT_ASCII_LINES:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_LINE_LIMIT",
            "The result ASCII input exceeds the bounded line limit.",
            maximum_lines=MAX_RESULT_ASCII_LINES,
        )
    remainder = data.replace(b"\r\n", b"")
    if b"\r" in remainder or b"\n" in remainder or not data.endswith(b"\r\n\r\n"):
        raise _fail(
            "SHIMADZU_RESULT_ASCII_LINE_ENDING_INVALID",
            "The exact result ASCII profile requires complete CRLF records.",
        )
    try:
        text = data.decode("ascii", errors="strict")
    except UnicodeDecodeError as error:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_ENCODING_UNSUPPORTED",
            "The exact result ASCII profile requires single-byte ASCII text.",
        ) from error
    lines = tuple(text.split("\r\n")[:-1])
    if len(lines) != line_count:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_LINE_ENDING_INVALID",
            "The result ASCII records could not be split without loss.",
        )
    for line in lines:
        if len(line) > MAX_LINE_CHARACTERS or any(
            ord(character) < 32 and character != "\t" for character in line
        ):
            raise _fail(
                "SHIMADZU_RESULT_ASCII_TEXT_INVALID",
                "A result ASCII record exceeds its bound or contains an unsupported control.",
            )
    return lines


def _sections(lines: tuple[str, ...]) -> dict[str, tuple[str, ...]]:
    positions = tuple(
        (index, line)
        for index, line in enumerate(lines)
        if line.startswith("[") and line.endswith("]")
    )
    if tuple(name for _index, name in positions) != SECTION_ORDER or positions[0][0] != 0:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_SECTION_INVALID",
            "The result ASCII section order is outside the exact supported profile.",
        )
    result: dict[str, tuple[str, ...]] = {}
    for item_index, (start, name) in enumerate(positions):
        end = positions[item_index + 1][0] if item_index + 1 < len(positions) else len(lines)
        result[name] = lines[start + 1 : end]
    return result


def _keyed_section(
    rows: tuple[str, ...],
    expected_keys: tuple[str, ...],
    *,
    section: str,
) -> dict[str, str]:
    if len(rows) != len(expected_keys) + 1 or rows[-1] != "":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PROFILE_UNSUPPORTED",
            "A fixed result ASCII section has an unsupported shape.",
            section=section,
        )
    result: dict[str, str] = {}
    for row, expected_key in zip(rows[:-1], expected_keys, strict=True):
        fields = row.split("\t")
        if len(fields) != 2 or fields[0] != expected_key:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_PROFILE_UNSUPPORTED",
                "A fixed result ASCII section has an unsupported field layout.",
                section=section,
            )
        result[expected_key] = fields[1]
    return result


def _count(text: str, *, field: str, maximum: int, positive: bool = False) -> int:
    pattern = _POSITIVE_INTEGER if positive else _NONNEGATIVE_INTEGER
    if len(text) > MAX_NUMERIC_LEXEME_CHARACTERS or pattern.fullmatch(text) is None:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_COUNT_INVALID",
            "A result ASCII count is outside the supported integer grammar.",
            field=field,
        )
    value = int(text)
    if value > maximum or positive and value < 1:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_COUNT_INVALID",
            "A result ASCII count is outside the supported bounded range.",
            field=field,
            maximum=maximum,
        )
    return value


def _decimal(text: str, *, field: str) -> tuple[Decimal, float]:
    if len(text) > MAX_NUMERIC_LEXEME_CHARACTERS or _DECIMAL.fullmatch(text) is None:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_NUMBER_INVALID",
            "A result ASCII numeric field is outside the supported decimal grammar.",
            field=field,
        )
    try:
        exact = Decimal(text)
        value = float(exact)
    except (InvalidOperation, OverflowError, ValueError) as error:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_NUMBER_INVALID",
            "A result ASCII numeric field is invalid.",
            field=field,
        ) from error
    if not exact.is_finite() or not isfinite(value):
        raise _fail(
            "SHIMADZU_RESULT_ASCII_NUMBER_INVALID",
            "A result ASCII numeric field must be finite.",
            field=field,
        )
    if Decimal(str(value)) != exact:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_LOSSY_FLOAT",
            "A result ASCII numeric field cannot be represented exactly by the canonical model.",
            field=field,
        )
    return exact, value


def _parse_peaks(rows: tuple[str, ...]) -> tuple[ShimadzuResultPeak, ...]:
    if len(rows) < 3 or rows[-1] != "":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PEAK_TABLE_INVALID",
            "The result ASCII peak table is incomplete.",
        )
    count_fields = rows[0].split("\t")
    if len(count_fields) != 2 or count_fields[0] != "# of Peaks":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PEAK_TABLE_INVALID",
            "The result ASCII peak count field is missing.",
        )
    peak_count = _count(count_fields[1], field="peak_count", maximum=MAX_PEAKS, positive=True)
    if tuple(rows[1].split("\t")) != PEAK_HEADERS or len(rows[2:-1]) != peak_count:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PEAK_COUNT_MISMATCH",
            "The declared result peak count does not match the exact table shape.",
            declared_count=peak_count,
            observed_count=len(rows[2:-1]),
        )
    peaks: list[ShimadzuResultPeak] = []
    previous_rt: Decimal | None = None
    for observation_order, row in enumerate(rows[2:-1], start=1):
        fields = row.split("\t")
        if len(fields) != len(PEAK_HEADERS):
            raise _fail(
                "SHIMADZU_RESULT_ASCII_PEAK_ROW_INVALID",
                "A result peak row does not match the exact column count.",
                observation_order=observation_order,
            )
        peak_number = _count(fields[0], field="peak_number", maximum=MAX_PEAKS, positive=True)
        if peak_number != observation_order:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_PEAK_ORDER_INVALID",
                "Source peak numbers must be contiguous and preserve table order.",
                observation_order=observation_order,
            )
        retention_exact, retention = _decimal(fields[1], field="retention_time")
        start_exact, start = _decimal(fields[2], field="start_time")
        end_exact, end = _decimal(fields[3], field="end_time")
        area_exact, area = _decimal(fields[4], field="area")
        height_exact, height = _decimal(fields[5], field="height")
        if not start_exact <= retention_exact <= end_exact:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_PEAK_BOUNDARY_INVALID",
                "Peak start, retention, and end times are inconsistent.",
                observation_order=observation_order,
            )
        if previous_rt is not None and retention_exact <= previous_rt:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_RETENTION_ORDER_INVALID",
                "Peak retention times must be strictly increasing in source order.",
                observation_order=observation_order,
            )
        if area_exact < 0 or height_exact < 0:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_RESPONSE_INVALID",
                "Peak area and height must be nonnegative in the exact profile.",
                observation_order=observation_order,
            )
        if fields[9] or fields[10]:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_IDENTIFICATION_UNSUPPORTED",
                "Identified compounds are outside the exact unassigned result profile.",
                observation_order=observation_order,
            )
        previous_rt = retention_exact
        peaks.append(
            ShimadzuResultPeak(
                peak_number,
                observation_order,
                fields[1],
                retention,
                fields[2],
                start,
                fields[3],
                end,
                fields[4],
                area,
                fields[5],
                height,
            )
        )
    return tuple(peaks)


def _parse_chromatogram(rows: tuple[str, ...]) -> tuple[int, int, Decimal, Decimal]:
    if len(rows) < 7 or rows[-1] != "":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_INVALID",
            "The same-file chromatogram section is incomplete.",
        )
    expected_keys = (
        "Interval(msec)",
        "# of Points",
        "Start Time(min)",
        "End Time(min)",
    )
    values: dict[str, str] = {}
    for row, expected_key in zip(rows[:4], expected_keys, strict=True):
        fields = row.split("\t")
        if len(fields) != 2 or fields[0] != expected_key:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_INVALID",
                "The same-file chromatogram header is outside the exact profile.",
            )
        values[expected_key] = fields[1]
    interval = _count(
        values["Interval(msec)"],
        field="chromatogram_interval_ms",
        maximum=1_000_000,
        positive=True,
    )
    point_count = _count(
        values["# of Points"],
        field="chromatogram_point_count",
        maximum=MAX_CHROMATOGRAM_POINTS,
        positive=True,
    )
    start_exact, _start = _decimal(values["Start Time(min)"], field="chromatogram_start")
    end_exact, _end = _decimal(values["End Time(min)"], field="chromatogram_end")
    if start_exact > end_exact or rows[4] != "R.Time (min)\tIntensity":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_INVALID",
            "The same-file chromatogram time boundary or column header is invalid.",
        )
    data_rows = rows[5:-1]
    if len(data_rows) != point_count:
        raise _fail(
            "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_COUNT_MISMATCH",
            "The declared chromatogram point count does not match the table.",
            declared_count=point_count,
            observed_count=len(data_rows),
        )
    previous_time: Decimal | None = None
    for row in data_rows:
        fields = row.split("\t")
        if len(fields) != 2:
            raise _fail(
                "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_INVALID",
                "A same-file chromatogram row has an invalid shape.",
            )
        time_exact, _time = _decimal(fields[0], field="chromatogram_time")
        _decimal(fields[1], field="chromatogram_intensity")
        if (
            time_exact < start_exact
            or time_exact > end_exact
            or previous_time is not None
            and time_exact <= previous_time
        ):
            raise _fail(
                "SHIMADZU_RESULT_ASCII_CHROMATOGRAM_INVALID",
                "Same-file chromatogram times are outside bounds or not strictly increasing.",
            )
        previous_time = time_exact
    return interval, point_count, start_exact, end_exact


def read_result_ascii(path: Path) -> ShimadzuResultAsciiData:
    """Read one exact LabSolutions 5.82 GC-2014 SFID1/Ch1 result export."""
    data = _read_bytes(path)
    sections = _sections(_lines(data))
    header = _keyed_section(sections["[Header]"], HEADER_KEYS, section="Header")
    file_information = _keyed_section(
        sections["[File Information]"], FILE_INFORMATION_KEYS, section="File Information"
    )
    _keyed_section(
        sections["[Sample Information]"],
        SAMPLE_INFORMATION_KEYS,
        section="Sample Information",
    )
    _keyed_section(sections["[Original Files]"], ORIGINAL_FILES_KEYS, section="Original Files")
    file_description = sections["[File Description]"]
    if len(file_description) != 2 or "\t" in file_description[0] or file_description[1] != "":
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PROFILE_UNSUPPORTED",
            "The File Description section has an unsupported shape.",
        )
    configuration = _keyed_section(
        sections["[Configuration]"], CONFIGURATION_KEYS, section="Configuration"
    )
    expected_profile = {
        "application_name": header["Application Name"] == "LabSolutions",
        "software_version": header["Version"] == "5.82",
        "file_type": file_information["Type"] == "Data File",
        "instrument_model": configuration["Instrument Name"] == "GC-2014",
        "detector_count": configuration["# of Detectors"] == "1",
        "detector_id": configuration["Detector ID"] == "DET#1",
        "detector_name": configuration["Detector Name"] == "SFID1",
        "channel_count": configuration["# of Channels"] == "1",
    }
    if not all(expected_profile.values()):
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PROFILE_UNSUPPORTED",
            "The result ASCII producer or instrument profile is unsupported.",
        )
    peaks = _parse_peaks(sections["[Peak Table(Ch1)]"])
    compound_results = sections["[Compound Results(Ch1)]"]
    if compound_results != ("# of IDs\t0", ""):
        raise _fail(
            "SHIMADZU_RESULT_ASCII_IDENTIFICATION_UNSUPPORTED",
            "Compound-result rows are outside the exact unassigned result profile.",
        )
    interval, point_count, chromatogram_start, chromatogram_end = _parse_chromatogram(
        sections["[Chromatogram (Ch1)]"]
    )
    if any(
        Decimal(peak.start_time_text) < chromatogram_start
        or Decimal(peak.retention_time_text) < chromatogram_start
        or Decimal(peak.retention_time_text) > chromatogram_end
        or Decimal(peak.end_time_text) > chromatogram_end
        for peak in peaks
    ):
        raise _fail(
            "SHIMADZU_RESULT_ASCII_PEAK_RANGE_INVALID",
            "A result peak or integration boundary is outside the same-file chromatogram range.",
        )
    return ShimadzuResultAsciiData(
        header["Application Name"],
        header["Version"],
        configuration["Instrument Name"],
        configuration["Detector Name"],
        "Ch1",
        "min",
        peaks,
        interval,
        point_count,
        len(data),
        hashlib.sha256(data).hexdigest(),
    )
